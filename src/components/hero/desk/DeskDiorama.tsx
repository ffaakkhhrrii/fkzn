import React, { useEffect, useRef } from 'react';
import { DESK_ART, DESK_META } from './art.generated';
import { mountDesk } from './live';
import './desk.css';

export interface DeskDioramaProps {
  /** Pictures for the wall frame, shown one at a time; opening the frame shows the next.
   *  Any aspect ratio: each is cropped to fill the mat opening. */
  frameImages?: string[];
  className?: string;
  /** Called with a route (work, writing, about, awards, contact) when an object is touched. */
  onOpen?: (route: string) => void;
  /** Called once the drawing is in the page, with its root element. */
  onReady?: (root: HTMLElement) => void;
}

const LABEL =
  'An isometric corner of a work desk against a wall: a monitor scrolling through a long Kotlin file, a mechanical ' +
  'keyboard, a mouse on a pad, a small PC tower with a glass side and spinning fans, a mug of hot coffee, a wall ' +
  'shelf of books with a trophy, and a framed picture. Each labelled object opens part of the site.';

/**
 * The desk diorama. The art is static SVG markup generated by scripts/desk/build.mjs;
 * everything that moves is driven by live.ts after mount.
 */
const DeskDiorama: React.FC<DeskDioramaProps> = ({ frameImages, className, onOpen, onReady }) => {
  const root = useRef<HTMLDivElement>(null);
  const images = (frameImages ?? []).join('\n');
  // live.ts mounts once per picture list; it reads the latest callbacks through refs
  const open = useRef(onOpen);
  open.current = onOpen;
  const ready = useRef(onReady);
  ready.current = onReady;

  useEffect(() => {
    if (!root.current) return;
    const stop = mountDesk(root.current, {
      frameImages: images ? images.split('\n') : [],
      onOpen: (route) => open.current?.(route),
    });
    ready.current?.(root.current);
    return stop;
  }, [images]);

  return (
    <div ref={root} className={`desk${className ? ` ${className}` : ''}`} data-desk>
      <svg
        className="desk-svg"
        viewBox={`0 0 ${DESK_META.width} ${DESK_META.height}`}
        role="img"
        aria-label={LABEL}
        dangerouslySetInnerHTML={{ __html: DESK_ART }}
      />
      <span className="sr-only" role="status" aria-live="polite" data-desk-status />
    </div>
  );
};

export default DeskDiorama;
