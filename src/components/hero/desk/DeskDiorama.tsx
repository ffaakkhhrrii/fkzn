import React, { useEffect, useRef } from 'react';
import { DESK_ART, DESK_META } from './art.generated';
import { mountDesk } from './live';
import './desk.css';

export interface DeskDioramaProps {
  /** Pictures for the wall frame, shown one at a time; a touch on the frame shows the next.
   *  Any aspect ratio: each is cropped to fill the mat opening. */
  frameImages?: string[];
  className?: string;
}

const LABEL =
  'An isometric corner of a work desk against a wall: a monitor scrolling through a long Kotlin file, a mechanical ' +
  'keyboard, a mouse on a pad, a small PC tower with a glass side and spinning fans, a mug of hot coffee, a wall ' +
  'shelf of books with a trophy, and a framed picture. The monitor, the mug and the frame react when touched.';

/**
 * The desk diorama. The art is static SVG markup generated by scripts/desk/build.mjs;
 * everything that moves is driven by live.ts after mount.
 */
const DeskDiorama: React.FC<DeskDioramaProps> = ({ frameImages, className }) => {
  const root = useRef<HTMLDivElement>(null);
  const images = (frameImages ?? []).join('\n');

  useEffect(() => {
    if (!root.current) return;
    return mountDesk(root.current, { frameImages: images ? images.split('\n') : [] });
  }, [images]);

  return (
    <div ref={root} className={`desk${className ? ` ${className}` : ''}`} data-desk>
      <svg
        className="desk-svg"
        viewBox={`0 0 ${DESK_META.width} ${DESK_META.height}`}
        role="group"
        aria-label={LABEL}
        dangerouslySetInnerHTML={{ __html: DESK_ART }}
      />
      <span className="desk-hint" data-desk-hint aria-hidden="true" />
      <span className="sr-only" role="status" aria-live="polite" data-desk-status />
    </div>
  );
};

export default DeskDiorama;
